"""Monthly cost model: embedded/low-cost store vs managed vector DBs at 100K / 1M / 10M vectors.

Every price is a named constant below with its source and retrieval date; change a constant and re-run
(`python -m evaluation.cost_model`) to regenerate evaluation/cost_analysis.md.
Vector size: 384-d float32 = 1,536 B. Stored payload (chunk text ~500 B + metadata ~500 B) is added: ~2.5 KB/vector total.
"""
from pathlib import Path

DIM = 384
BYTES_VECTOR = DIM * 4
BYTES_PAYLOAD = 1000
BYTES_PER_VEC = BYTES_VECTOR + BYTES_PAYLOAD           # ~2.5 KB with chunk text + metadata
INDEX_OVERHEAD = 1.3                                   # index multiplier (assumption)

# ---- Prices (USD) ----
PINECONE_MIN_MONTHLY = 50.0        # Standard plan minimum usage   - pinecone.io/pricing, retrieved 2026-10-18
PINECONE_STORAGE_GB = 0.33         # serverless storage $/GB-month - same page
PINECONE_READ_PER_M = 17.0         # read units $/million; page gives $16-$18 by region (midpoint)
PINECONE_WRITE_PER_M = 4.25        # write units $/million; page gives $4-$4.50 (midpoint)
QDRANT_FREE_TIER_RAM_GB = 1.0      # free cluster: 1 GB RAM / 4 GB disk - qdrant.tech/pricing, retrieved 2026-10-18
EC2_T4G_MEDIUM_MONTH = 24.53       # 2 vCPU / 4 GiB, us-east-1 on-demand $0.0336/h - third-party aggregator (holori.com, Jul 2026)
EC2_T4G_LARGE_MONTH = 49.06        # 2 vCPU / 8 GiB, $0.0672/h - same source
EBS_GP3_GB = 0.08                  # AWS list price $/GB-month (us-east-1)
S3_STD_GB = 0.023                  # AWS list price $/GB-month (us-east-1)
HOURS = 730

QUERIES_PER_MONTH = 15_000         # ~500 queries/day: the "large but lightly-queried index" from the brief
RU_PER_QUERY_MIN = 0.25            # Pinecone: a query reads 1 RU per GB of namespace (min 0.25) - from Pinecone docs, verify
WRITE_UNITS_PER_VECTOR = 2.5       # 1 WU per KB written; ~2.5 KB per vector


def gb(n_vectors: int) -> float:
    return n_vectors * BYTES_PER_VEC / 1e9


def model(n: int, qpm: int = QUERIES_PER_MONTH) -> dict:
    data_gb = gb(n)
    stored_gb = data_gb * INDEX_OVERHEAD
    # managed
    read_units = max(RU_PER_QUERY_MIN, data_gb) * qpm
    pinecone = max(PINECONE_MIN_MONTHLY,
                   data_gb * PINECONE_STORAGE_GB + read_units / 1e6 * PINECONE_READ_PER_M)
    pinecone_ingest_once = n * WRITE_UNITS_PER_VECTOR / 1e6 * PINECONE_WRITE_PER_M
    ram_gb = max(1.0, stored_gb)                       # an in-memory index must fit in RAM
    # Qdrant Cloud publishes no rate card, so only its free tier is modelled (None = cannot be priced from public data).
    qdrant_cloud = 0.0 if ram_gb <= QDRANT_FREE_TIER_RAM_GB else None
    # self-hosted low-cost
    ebs = stored_gb * 1.5 * EBS_GP3_GB                 # 50% free-space headroom
    s3 = stored_gb * S3_STD_GB
    vm = EC2_T4G_MEDIUM_MONTH if stored_gb <= 2 else EC2_T4G_LARGE_MONTH
    return {"n": n, "data_gb": data_gb, "stored_gb": stored_gb,
            "pinecone_serverless": pinecone, "pinecone_ingest_once": pinecone_ingest_once,
            "qdrant_cloud_est": qdrant_cloud, "marginal_ebs": ebs, "marginal_s3": s3,
            "dedicated_vm_ebs": vm + ebs}


def render() -> str:
    rows = [model(n) for n in (100_000, 1_000_000, 10_000_000)]
    f = lambda x: f"${x:,.2f}"  # noqa: E731
    out = ["# Cost Analysis: low-cost embedded store (LanceDB) vs managed vector DBs\n",
           "_Generated by `python -m evaluation.cost_model`; edit the constants there and re-run. Prices retrieved 2026-10-18._\n",
           "## 1. Monthly cost at 100K / 1M / 10M vectors\n",
           "| Vectors | Data size* | Pinecone Serverless (Standard) | Qdrant Cloud | **Self-host, marginal on an existing host (EBS)** | Self-host, S3-backed (storage only) | **Self-host, dedicated VM + EBS** |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['n']:,} | {r['data_gb']:.2f} GB | {f(r['pinecone_serverless'])} | {'$0.00 (free 1 GB tier)' if r['qdrant_cloud_est'] == 0 else 'not published'} | "
                   f"**{f(r['marginal_ebs'])}** | {f(r['marginal_s3'])} | **{f(r['dedicated_vm_ebs'])}** |")
    out += [
        "\n\\* vectors (1,536 B) + stored chunk text/metadata (~1 KB) = ~2.5 KB per vector. Disk/RAM use a further x1.3 for index overhead.\n",
        "## 2. How to read this table honestly\n",
        "* **Against Pinecone Serverless the saving is real but nowhere near 99%.** Its $50/month Standard minimum is the floor at all three "
        "scales for a lightly-queried index (storage + reads stay under $50 even at 10M vectors), so the comparison is a flat $50 against our cost.",
        "* **Marginal vs dedicated.** If the vector store rides on a server you already run (here: the FastAPI container) the marginal cost is "
        "disk, i.e. cents. If you must provision a VM *for* the index, the saving at 10M vectors is about zero against Pinecone's minimum (last column).",
        "* **Qdrant Cloud publishes no rate card** (usage-based on vCPU/RAM/disk; only a calculator), so only its free 1 GB tier is modelled: "
        "it covers 100K vectors at $0. Larger sizes are marked 'not published' rather than guessed (one third-party figure of ~$57/GB-RAM-month looked implausible and was discarded).",
        "* An earlier draft used `$70 / $96 / $288` 'managed pod' baselines that were not traceable to a current price list; they are not used.\n",
        "## 3. Assumptions\n",
        "| Assumption | Value | Source |", "|---|---|---|",
        f"| Embedding | BAAI/bge-small-en-v1.5, {DIM}-d float32 = {BYTES_VECTOR:,} B/vector | model card |",
        f"| Per-vector payload (chunk text + metadata) | {BYTES_PAYLOAD:,} B | order of magnitude for 500-char chunks |",
        f"| Index overhead | x{INDEX_OVERHEAD} | assumption (IVF-PQ is smaller, HNSW larger) |",
        f"| Query volume | {QUERIES_PER_MONTH:,}/month (~500/day) | 'lightly-queried' per the brief; LLM generation cost is identical on both sides and excluded |",
        f"| Pinecone Standard | ${PINECONE_MIN_MONTHLY:.0f}/mo minimum; ${PINECONE_STORAGE_GB}/GB-mo storage; ${PINECONE_READ_PER_M}/M read units; ${PINECONE_WRITE_PER_M}/M write units | pinecone.io/pricing (page gives $16-18 read and $4-4.5 write; midpoints used) |",
        f"| Pinecone read units | 1 RU per GB of namespace per query, min {RU_PER_QUERY_MIN} | Pinecone docs, from memory; verify |",
        f"| Qdrant Cloud | free tier only: {QDRANT_FREE_TIER_RAM_GB:.0f} GB RAM / 4 GB disk; paid clusters not priced | qdrant.tech/pricing (no public rate card) |",
        f"| EC2 us-east-1 on-demand | t4g.medium ${EC2_T4G_MEDIUM_MONTH}/mo (index <= 2 GB), t4g.large ${EC2_T4G_LARGE_MONTH}/mo | third-party aggregator; check aws.amazon.com/ec2/pricing |",
        f"| EBS gp3 / S3 Standard | ${EBS_GP3_GB}/GB-mo (x1.5 headroom) / ${S3_STD_GB}/GB-mo | AWS list prices |",
        "| Embedding compute | $0, local ONNX model on the same CPU | a hosted embedding API would add the same cost to both sides |",
        "| Replication / HA | none (single node) on the low-cost side | trade-off accepted, see below |",
        "\nOne-time Pinecone ingest write cost: " + ", ".join(f"{r['n']:,} vectors = {f(r['pinecone_ingest_once'])}" for r in rows) + ".\n",
        "## 4. Trade-offs knowingly accepted\n",
        "1. **Single node, no HA/replication.** A host failure means downtime until restore. The index is rebuildable from the corpus in minutes; keep a copy on S3.",
        "2. **One writer at a time.** Embedded stores take a file lock; ingestion is serialised in-process.",
        "3. **Ceiling on QPS and tail latency.** See `results_scale.json`; a managed in-memory index wins at high QPS and strict p99 SLAs.",
        "4. **You own ops** (patching, backups, monitoring; see HANDOVER.md). The table excludes engineer time, which is the real cost of self-hosting.",
        "5. **Local-mode Qdrant is brute-force** (no HNSW); fine at 100K, impractical at 1M+. Use a Qdrant server for larger indexes.",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    (Path(__file__).resolve().parent / "cost_analysis.md").write_text(text, encoding="utf-8")
    print(text)
